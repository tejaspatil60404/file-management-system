const mongoose = require('mongoose');

// Define the schema (structure) of the File document
const fileSchema = new mongoose.Schema({
  originalName: {
    type: String,
    required: true
  },
  fileName: {
    type: String,
    required: true
  },
  path: {
    type: String,
    required: true
  },
  size: {
    type: Number,
    required: true
  },
  uploadedAt: {
    type: Date,
    default: Date.now
  }
});

// Export the model so we can use it in controllers
module.exports = mongoose.model('File', fileSchema);
